-- Wishlist moved from browser storage to the server: one row per user and hotel.
create table if not exists wishlists (
    id bigint generated by default as identity primary key,
    user_id bigint not null references users (id) on delete cascade,
    hotel_id bigint not null references hotels (id) on delete cascade,
    created_at timestamp(6) not null default now(),
    constraint uk_wishlists_user_hotel unique (user_id, hotel_id)
);

-- Avatar moved from a data URL in localStorage to an uploaded image.
alter table users add column if not exists avatar_url varchar(255);

-- rating_avg used to be a static value; make it match the reviews that already exist.
update hotels h
set rating_avg = r.avg_rating
from (select hotel_id, avg(rating) as avg_rating from reviews group by hotel_id) r
where h.id = r.hotel_id;

-- The application already enforces one account per email and one review per user and hotel; these indexes
-- also close the race between two concurrent requests. Older data may already contain duplicates, and failing
-- here would stop the application from starting, so in that case the index is skipped with a warning and must
-- be added by a later migration once the duplicates are resolved.
do $$
begin
    if exists (select 1 from users group by lower(email) having count(*) > 1) then
        raise warning 'users has duplicate emails: unique index uk_users_email_lower was NOT created';
    else
        create unique index if not exists uk_users_email_lower on users (lower(email));
    end if;

    if exists (select 1 from reviews group by user_id, hotel_id having count(*) > 1) then
        raise warning 'reviews has duplicate (user_id, hotel_id): unique index uk_reviews_user_hotel was NOT created';
    else
        create unique index if not exists uk_reviews_user_hotel on reviews (user_id, hotel_id);
    end if;
end $$;
