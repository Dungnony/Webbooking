-- Schema as Hibernate generated it from the entities before Flyway was introduced.
-- Existing databases are baselined at this version (see FlywayConfig) and never run this file;
-- it only builds a brand-new empty database.

create table app_config (
    config_key varchar(255) not null,
    config_value varchar(255),
    primary key (config_key)
);

create table booking_request (
    new_check_in date,
    new_check_out date,
    booking_id bigint,
    created_at timestamp(6),
    id bigint generated by default as identity,
    processed_at timestamp(6),
    processed_by bigint,
    admin_response TEXT,
    reason TEXT,
    status varchar(255) check (status in ('PENDING','APPROVED','REJECTED')),
    type varchar(255) check (type in ('CANCEL','CHANGE_DATE')),
    primary key (id)
);

create table booking_rooms (
    price float(53),
    quantity integer,
    booking_id bigint,
    id bigint generated by default as identity,
    room_id bigint,
    primary key (id)
);

create table bookings (
    check_in_date date,
    check_out_date date,
    total_price float(53),
    created_at timestamp(6),
    hotel_id bigint,
    id bigint generated by default as identity,
    user_id bigint,
    payment_status varchar(255) check (payment_status in ('UNPAID','PAID','REFUNDED')),
    status varchar(255) check (status in ('PENDING','CONFIRMED','REJECTED','CANCELLED')),
    primary key (id)
);

create table hotels (
    rating_avg float(53),
    created_at timestamp(6),
    id bigint generated by default as identity,
    address varchar(255),
    city varchar(255),
    description TEXT,
    image_url varchar(255),
    name varchar(255),
    status varchar(255),
    primary key (id)
);

create table notifications (
    is_read boolean,
    created_at timestamp(6),
    id bigint generated by default as identity,
    user_id bigint,
    message TEXT,
    title varchar(255),
    primary key (id)
);

create table reviews (
    rating integer,
    created_at timestamp(6),
    hotel_id bigint,
    id bigint generated by default as identity,
    user_id bigint,
    comment TEXT,
    primary key (id)
);

create table room_image (
    id bigint generated by default as identity,
    room_id bigint,
    image_url varchar(255),
    primary key (id)
);

create table rooms (
    capacity integer,
    price_per_night float(53),
    quantity integer,
    created_at timestamp(6),
    hotel_id bigint,
    id bigint generated by default as identity,
    description TEXT,
    name varchar(255),
    type varchar(255),
    primary key (id)
);

create table users (
    id bigint generated by default as identity,
    email varchar(255) not null,
    password varchar(255) not null,
    role varchar(255) default 'USER' not null check (role in ('USER','ADMIN')),
    username varchar(255) not null unique,
    primary key (id)
);

